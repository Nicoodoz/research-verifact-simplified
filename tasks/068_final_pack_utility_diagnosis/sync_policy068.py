from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]


def edit(rel, replacements, prefix=None):
    path = ROOT / rel
    raw = path.read_bytes()
    newline = b"\r\n" if b"\r\n" in raw else b"\n"
    if raw.count(b"\n") != raw.count(newline):
        raise RuntimeError(f"mixed line endings: {rel}")
    text = raw.decode("utf-8-sig").replace("\r\n", "\n")
    for old, new in replacements:
        if text.count(old) != 1:
            raise RuntimeError(f"expected one occurrence in {rel}: {old[:70]}")
        text = text.replace(old, new, 1)
    if prefix:
        if prefix in text:
            raise RuntimeError(f"already prefixed: {rel}")
        text = prefix + text
    path.write_bytes(text.replace("\n", newline.decode()).encode("utf-8"))


