for name, pairs in CHANGES.items():
    path = ROOT / name
    original = path.read_bytes()
    data = original
    for old, new in pairs:
        a, b = old.encode("utf-8"), new.encode("utf-8")
        count = data.count(a)
        assert count == 1, (name, old[:40], count)
        data = data.replace(a, b)
    path.write_bytes(data)
    assert original.count(b"\r\n") == data.count(b"\r\n")
    print(name, "updated", len(pairs), "preserved_existing_newlines")
